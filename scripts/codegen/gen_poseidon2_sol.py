#!/usr/bin/env python3
"""Generate contracts/lib/Poseidon2.sol (BN254, t=4) from poseidon2_bn254_t4.json.

The constants are Barretenberg's (the same ones Noir's poseidon2_permutation uses);
test/Poseidon2.test.js checks that the contract matches bb.js poseidon2Hash.
Usage: python3 scripts/codegen/gen_poseidon2_sol.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
C = json.load(open(os.path.join(HERE, "poseidon2_bn254_t4.json")))
RC, DIAG = C["rc"], C["diag"]

out = []
w = out.append
w("// SPDX-License-Identifier: MIT")
w("// AUTO-GENERATED by scripts/codegen/gen_poseidon2_sol.py. Do not edit by hand.")
w("pragma solidity ^0.8.24;")
w("")
w("/// @title Poseidon2 (BN254, t=4) compatible with Barretenberg / Noir")
w("/// @notice hash2(a, b) == Poseidon2 sponge hash of [a, b] (bb.js poseidon2Hash).")
w("library Poseidon2 {")
w("    uint256 internal constant P = 21888242871839275222246405745257275088548364400416034343698204186575808495617;")
w("")
w("    function hash2(uint256 a, uint256 b) internal pure returns (uint256) {")
w("        require(a < P && b < P, \"Poseidon2: input not in field\");")
w("        // sponge: state = [a, b, 0, IV], IV = 2 * 2^64")
w("        return _perm(a, b, 0, 2 << 64);")
w("    }")
w("")
w("    function _sbox(uint256 x) private pure returns (uint256) {")
w("        uint256 x2 = mulmod(x, x, P);")
w("        return mulmod(mulmod(x2, x2, P), x, P);")
w("    }")
w("")
w("    // M4 = [[5,7,1,3],[4,6,1,1],[1,3,5,7],[1,1,4,6]]")
w("    function _ext(uint256 s0, uint256 s1, uint256 s2, uint256 s3)")
w("        private pure returns (uint256, uint256, uint256, uint256)")
w("    {")
w("        return (")
w("            addmod(addmod(mulmod(5, s0, P), mulmod(7, s1, P), P), addmod(s2, mulmod(3, s3, P), P), P),")
w("            addmod(addmod(mulmod(4, s0, P), mulmod(6, s1, P), P), addmod(s2, s3, P), P),")
w("            addmod(addmod(s0, mulmod(3, s1, P), P), addmod(mulmod(5, s2, P), mulmod(7, s3, P), P), P),")
w("            addmod(addmod(s0, s1, P), addmod(mulmod(4, s2, P), mulmod(6, s3, P), P), P)")
w("        );")
w("    }")
w("")
w("    function _full(uint256 s0, uint256 s1, uint256 s2, uint256 s3, uint256 c0, uint256 c1, uint256 c2, uint256 c3)")
w("        private pure returns (uint256, uint256, uint256, uint256)")
w("    {")
w("        return _ext(_sbox(addmod(s0, c0, P)), _sbox(addmod(s1, c1, P)), _sbox(addmod(s2, c2, P)), _sbox(addmod(s3, c3, P)));")
w("    }")
w("")
w("    function _partial(uint256 s0, uint256 s1, uint256 s2, uint256 s3, uint256 c0)")
w("        private pure returns (uint256, uint256, uint256, uint256)")
w("    {")
w("        s0 = _sbox(addmod(s0, c0, P));")
w("        uint256 t = addmod(addmod(s0, s1, P), addmod(s2, s3, P), P);")
w(f"        return (")
w(f"            addmod(mulmod(s0, {DIAG[0]}, P), t, P),")
w(f"            addmod(mulmod(s1, {DIAG[1]}, P), t, P),")
w(f"            addmod(mulmod(s2, {DIAG[2]}, P), t, P),")
w(f"            addmod(mulmod(s3, {DIAG[3]}, P), t, P)")
w(f"        );")
w("    }")
w("")
w("    function _perm(uint256 s0, uint256 s1, uint256 s2, uint256 s3) private pure returns (uint256) {")
w("        (s0, s1, s2, s3) = _ext(s0, s1, s2, s3);")
for r in range(64):
    if r < 4 or r >= 60:
        c = RC[r]
        w(f"        (s0, s1, s2, s3) = _full(s0, s1, s2, s3, {c[0]}, {c[1]}, {c[2]}, {c[3]});")
    else:
        w(f"        (s0, s1, s2, s3) = _partial(s0, s1, s2, s3, {RC[r][0]});")
w("        return s0;")
w("    }")
w("}")
open(os.path.join(ROOT, "contracts", "lib", "Poseidon2.sol"), "w").write("\n".join(out) + "\n")
print("wrote contracts/lib/Poseidon2.sol")
