import "dotenv/config";
import hardhatToolboxMochaEthers from "@nomicfoundation/hardhat-toolbox-mocha-ethers";
import { defineConfig } from "hardhat/config";

// Offline builds: SOLC_PATH_0_8_26 / SOLC_PATH_0_8_28 point to local solc binaries
// to skip downloading compilers from binaries.soliditylang.org.
const solc = (version, runs) => ({
  version,
  ...(process.env[`SOLC_PATH_${version.replaceAll(".", "_")}`]
    ? { path: process.env[`SOLC_PATH_${version.replaceAll(".", "_")}`] }
    : {}),
  settings: { optimizer: { enabled: true, runs } },
});

const RPC_URL = process.env.RPC_URL || "https://rpc-amoy.polygon.technology";
const DEPLOYER_PRIVATE_KEY = process.env.DEPLOYER_PRIVATE_KEY ? [process.env.DEPLOYER_PRIVATE_KEY] : [];

export default defineConfig({
  plugins: [hardhatToolboxMochaEthers],
  solidity: {
    compilers: [solc("0.8.26", 200)],
    // UltraHonk verifiers generated by bb (npm run build:circuits) require >= 0.8.27.
    overrides: Object.fromEntries(
      ["Spend", "Compliance", "Balance"].map((n) => [`contracts/verifiers/${n}Verifier.sol`, solc("0.8.28", 1)])
    ),
  },
  networks: {
    amoy: { type: "http", url: RPC_URL, chainId: 80002, accounts: DEPLOYER_PRIVATE_KEY },
    sepolia: {
      type: "http",
      url: process.env.SEPOLIA_RPC_URL || "https://rpc.sepolia.org",
      chainId: 11155111,
      accounts: DEPLOYER_PRIVATE_KEY,
    },
    localhost: { type: "http", url: "http://127.0.0.1:8545", chainId: 31337 },
  },
  paths: { sources: "./contracts", tests: { mocha: "./test" }, cache: "./cache", artifacts: "./artifacts" },
});
