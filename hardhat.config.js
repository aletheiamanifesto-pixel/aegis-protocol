// Offline builds: SOLCJS_PATH (0.8.26) and SOLCJS_PATH_0_8_28 point to local soljson.js files
// (npm package "solc") to skip downloading compilers from binaries.soliditylang.org.
const _solcjs = { "0.8.26": process.env.SOLCJS_PATH, "0.8.28": process.env.SOLCJS_PATH_0_8_28 };
if (Object.values(_solcjs).some(Boolean)) {
  const { subtask } = require("hardhat/config");
  const { TASK_COMPILE_SOLIDITY_GET_SOLC_BUILD } = require("hardhat/builtin-tasks/task-names");
  subtask(TASK_COMPILE_SOLIDITY_GET_SOLC_BUILD, async (args, hre, runSuper) => {
    const path = _solcjs[args.solcVersion];
    if (!path) return runSuper();
    return { compilerPath: path, isSolcJs: true, version: args.solcVersion, longVersion: args.solcVersion };
  });
}

